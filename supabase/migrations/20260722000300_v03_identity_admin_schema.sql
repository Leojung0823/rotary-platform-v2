create trigger club_role_assignments_set_updated_at before update on public.club_role_assignments
for each row execute function public.set_updated_at();
create trigger member_invitations_set_updated_at before update on public.member_invitations
for each row execute function public.set_updated_at();
create trigger line_login_configs_set_updated_at before update on public.line_login_configs
for each row execute function public.set_updated_at();
create trigger line_identities_set_updated_at before update on public.line_identities
for each row execute function public.set_updated_at();
create trigger user_devices_set_updated_at before update on public.user_devices
for each row execute function public.set_updated_at();
create trigger line_oa_accounts_set_updated_at before update on public.line_oa_accounts
for each row execute function public.set_updated_at();
create trigger line_oa_followers_set_updated_at before update on public.line_oa_followers
for each row execute function public.set_updated_at();

alter table public.permissions enable row level security;
alter table public.role_definitions enable row level security;
alter table public.role_permissions enable row level security;
alter table public.club_role_assignments enable row level security;
alter table public.member_invitations enable row level security;
alter table public.invitation_logs enable row level security;
alter table public.line_login_configs enable row level security;
alter table public.line_oauth_states enable row level security;
alter table public.line_identities enable row level security;
alter table public.login_history enable row level security;
alter table public.user_devices enable row level security;
alter table public.notification_settings enable row level security;
alter table public.privacy_settings enable row level security;
alter table public.line_oa_accounts enable row level security;
