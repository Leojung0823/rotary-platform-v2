revoke all on table public.permissions, public.role_definitions, public.role_permissions,
  public.club_role_assignments, public.member_invitations, public.invitation_logs,
  public.line_login_configs, public.line_oauth_states, public.line_identities,
  public.login_history, public.user_devices, public.notification_settings,
  public.privacy_settings, public.line_oa_accounts, public.line_oa_followers,
  public.line_push_logs, public.line_webhooks from anon, authenticated;

grant select, insert, update on table public.permissions, public.role_definitions, public.role_permissions,
  public.club_role_assignments, public.member_invitations, public.line_login_configs,
  public.line_oauth_states, public.line_identities, public.user_devices,
  public.notification_settings, public.privacy_settings, public.line_oa_accounts,
  public.line_oa_followers to service_role;
grant select, insert on table public.invitation_logs, public.login_history,
  public.line_push_logs, public.line_webhooks to service_role;
grant update on table public.line_webhooks to service_role;
grant usage, select on sequence public.invitation_logs_id_seq, public.login_history_id_seq,
  public.line_webhooks_id_seq to service_role;

commit;
