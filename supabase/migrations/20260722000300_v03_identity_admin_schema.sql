  ('identity.read', '查看登入身份、裝置與紀錄'),
  ('identity.unbind', '解除 LINE Login 綁定'),
  ('oa.read', '查看 LINE OA 狀態'),
  ('oa.manage', '設定 LINE OA、配對與推播'),
  ('role.manage', '管理社級角色'),
  ('audit.read', '查看稽核紀錄'),
  ('finance.read', '查看財務身份範圍'),
  ('profile.self', '管理自己的資料與偏好');

