declare
  actor_id uuid := public.current_app_account_id();
  preview jsonb;
  credential public.event_checkin_qr_credentials;
  current_session public.event_checkin_sessions;
  target_event public.club_events;
  actor_membership_id uuid;
  existing_attendance public.event_attendances;
  created_attendance public.event_attendances;
begin
  preview := public.preview_event_qr_checkin(p_token);
  if preview->>'status' <> 'ready' then return preview; end if;

  select * into credential
  from public.event_checkin_qr_credentials
  where token_hash = encode(extensions.digest(p_token, 'sha256'), 'hex')
  for update;
  select * into current_session
  from public.event_checkin_sessions
  where id = credential.session_id
  for share;
  select * into target_event
  from public.club_events
  where id = credential.event_id and club_id = credential.club_id
  for share;
  actor_membership_id := public.current_checkin_membership_id(credential.club_id);

  if credential.invalidated_at is not null or credential.expires_at <= now()
     or current_session.session_status <> 'active' or current_session.expires_at <= now() then
    perform public.record_event_checkin_attempt(
      credential.club_id, credential.event_id, actor_membership_id, actor_id, 'qr', 'credential_expired'
    );
    return jsonb_build_object('status', 'credential_expired');
  end if;
  if actor_membership_id is null
     or target_event.id is null
     or target_event.event_status <> 'published'
     or not target_event.counts_for_attendance
     or not exists (
       select 1
       from public.event_checkin_settings as setting
       where setting.event_id = credential.event_id
         and setting.club_id = credential.club_id
         and setting.qr_enabled
         and now() between setting.opens_at and setting.closes_at
     ) then
    perform public.record_event_checkin_attempt(
      credential.club_id, credential.event_id, actor_membership_id, actor_id, 'qr', 'window_closed'
    );
    return jsonb_build_object('status', 'window_closed');
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(target_event.id::text || ':' || actor_membership_id::text, 0)
  );

  select * into existing_attendance
  from public.event_attendances
  where event_id = target_event.id
    and membership_id = actor_membership_id
    and attendance_status = 'active';
  if found then
    perform public.record_event_checkin_attempt(
      credential.club_id, credential.event_id, actor_membership_id, actor_id, 'qr', 'already_checked_in'
    );
    return jsonb_build_object(
      'status', 'already_checked_in',
      'attendance_id', existing_attendance.id,
      'event_id', target_event.id,
      'title', target_event.title,
      'checked_in_at', existing_attendance.checked_in_at,
      'idempotent', true
    );
  end if;

  insert into public.event_attendances (
    club_id, event_id, membership_id, checkin_session_id, checkin_method,
    checked_in_by_app_account_id, checkin_note
  ) values (
    credential.club_id, credential.event_id, actor_membership_id, current_session.id,
    'qr', actor_id, ''
  ) returning * into created_attendance;

  perform public.record_event_checkin_attempt(
    credential.club_id, credential.event_id, actor_membership_id, actor_id, 'qr', 'success'
  );
  insert into public.audit_logs (
    club_id, actor_app_account_id, action_key, subject_type, subject_id, metadata
  ) values (
    credential.club_id, actor_id, 'attendance.self_checked_in', 'event_attendance',
    created_attendance.id,
    jsonb_build_object(
      'event_id', target_event.id,
      'membership_id', actor_membership_id,
      'session_id', current_session.id,
      'method', 'qr'
    )
  );

  return jsonb_build_object(
    'status', 'success',
    'attendance_id', created_attendance.id,
    'event_id', target_event.id,
    'title', target_event.title,
    'checked_in_at', created_attendance.checked_in_at,
    'idempotent', false
  );
end;
$$;

create or replace function public.check_in_by_gps(
  p_event_id uuid,
  p_latitude numeric,
  p_longitude numeric,
  p_accuracy_meters numeric
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  actor_id uuid := public.current_app_account_id();
  target_event public.club_events;
  setting public.event_checkin_settings;
  actor_membership_id uuid;
  measured_distance numeric;
  existing_attendance public.event_attendances;
  created_attendance public.event_attendances;
begin
  if actor_id is null then
    raise exception using errcode = '42501', message = 'active_account_required';
  end if;

  select event.* into target_event
  from public.club_events as event
  where event.id = p_event_id;
  if not found then return jsonb_build_object('status', 'not_eligible'); end if;
  select * into setting
  from public.event_checkin_settings
  where event_id = target_event.id and club_id = target_event.club_id;
  actor_membership_id := public.current_checkin_membership_id(target_event.club_id);

  if actor_membership_id is null or setting.event_id is null or not setting.gps_enabled
     or target_event.event_status <> 'published' or not target_event.counts_for_attendance then
    perform public.record_event_checkin_attempt(
      target_event.club_id, target_event.id, actor_membership_id, actor_id, 'gps', 'not_eligible'
    );
    return jsonb_build_object('status', 'not_eligible');
  end if;
  if now() < setting.opens_at or now() > setting.closes_at then
    perform public.record_event_checkin_attempt(
      target_event.club_id, target_event.id, actor_membership_id, actor_id, 'gps', 'window_closed'
    );
    return jsonb_build_object('status', 'window_closed');
  end if;
  if p_latitude is null or p_latitude not between -90 and 90
     or p_longitude is null or p_longitude not between -180 and 180
     or p_accuracy_meters is null or p_accuracy_meters < 0 or p_accuracy_meters > 10000 then
    perform public.record_event_checkin_attempt(
      target_event.club_id, target_event.id, actor_membership_id, actor_id, 'gps', 'location_invalid'
    );
    return jsonb_build_object('status', 'location_invalid');
  end if;

  measured_distance := public.event_distance_meters(
    setting.latitude, setting.longitude, p_latitude, p_longitude
  );
  if p_accuracy_meters > setting.max_accuracy_meters then
    perform public.record_event_checkin_attempt(
      target_event.club_id, target_event.id, actor_membership_id, actor_id, 'gps',
      'accuracy_insufficient', p_accuracy_meters, measured_distance
    );
    return jsonb_build_object(
      'status', 'accuracy_insufficient',
      'accuracy_meters', round(p_accuracy_meters, 2),
      'required_accuracy_meters', setting.max_accuracy_meters
    );
  end if;
  if measured_distance > setting.radius_meters then
    perform public.record_event_checkin_attempt(
      target_event.club_id, target_event.id, actor_membership_id, actor_id, 'gps',
      'outside_radius', p_accuracy_meters, measured_distance
    );
    return jsonb_build_object(
      'status', 'outside_radius',
      'distance_meters', measured_distance,
      'radius_meters', setting.radius_meters
    );
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(target_event.id::text || ':' || actor_membership_id::text, 0)
  );
  select * into existing_attendance
  from public.event_attendances
  where event_id = target_event.id
    and membership_id = actor_membership_id
    and attendance_status = 'active';
  if found then
    perform public.record_event_checkin_attempt(
      target_event.club_id, target_event.id, actor_membership_id, actor_id, 'gps',
      'already_checked_in', p_accuracy_meters, measured_distance
    );
    return jsonb_build_object(
      'status', 'already_checked_in',
      'attendance_id', existing_attendance.id,
      'event_id', target_event.id,
      'title', target_event.title,
      'checked_in_at', existing_attendance.checked_in_at,
      'idempotent', true
    );
  end if;

  insert into public.event_attendances (
    club_id, event_id, membership_id, checkin_method,
    checked_in_by_app_account_id, checkin_note,
    location_accuracy_meters, distance_meters
  ) values (
    target_event.club_id, target_event.id, actor_membership_id, 'gps', actor_id, '',
    round(p_accuracy_meters, 2), measured_distance
  ) returning * into created_attendance;

  perform public.record_event_checkin_attempt(
    target_event.club_id, target_event.id, actor_membership_id, actor_id, 'gps',
    'success', p_accuracy_meters, measured_distance
  );
  insert into public.audit_logs (
    club_id, actor_app_account_id, action_key, subject_type, subject_id, metadata
  ) values (
    target_event.club_id, actor_id, 'attendance.self_checked_in', 'event_attendance',
    created_attendance.id,
    jsonb_build_object(
      'event_id', target_event.id,
      'membership_id', actor_membership_id,
      'method', 'gps',
      'accuracy_meters', round(p_accuracy_meters, 2),
      'distance_meters', measured_distance
    )
  );

  return jsonb_build_object(
    'status', 'success',
    'attendance_id', created_attendance.id,
    'event_id', target_event.id,
    'title', target_event.title,
    'checked_in_at', created_attendance.checked_in_at,
    'distance_meters', measured_distance,
    'idempotent', false
  );
end;
$$;

