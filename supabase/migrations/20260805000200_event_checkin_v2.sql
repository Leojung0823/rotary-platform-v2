create or replace function public.configure_event_checkin(
  p_club_id uuid,
  p_event_id uuid,
  p_gps_enabled boolean,
  p_qr_enabled boolean,
  p_latitude numeric,
  p_longitude numeric,
  p_radius_meters integer,
  p_max_accuracy_meters integer,
  p_opens_at timestamptz,
  p_closes_at timestamptz,
  p_qr_rotation_seconds integer default 45
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  actor_id uuid := public.current_app_account_id();
  target_event public.club_events;
  saved public.event_checkin_settings;
begin
  if actor_id is null or not public.current_can_manage_event_checkin(p_club_id) then
    raise exception using errcode = '42501', message = 'attendance_manage_required';
  end if;

  select * into target_event
  from public.club_events
  where id = p_event_id and club_id = p_club_id
  for share;
  if not found or target_event.event_status not in ('draft', 'published')
     or not target_event.counts_for_attendance then
    raise exception using errcode = '22023', message = 'event_not_checkin_eligible';
  end if;
  if not coalesce(p_gps_enabled, false) and not coalesce(p_qr_enabled, false) then
    raise exception using errcode = '22023', message = 'checkin_method_required';
  end if;
  if p_opens_at is null or p_closes_at is null or p_closes_at <= p_opens_at
     or p_opens_at < target_event.starts_at - interval '24 hours'
     or p_closes_at > target_event.ends_at + interval '24 hours'
     or p_qr_rotation_seconds is null
     or p_qr_rotation_seconds not between 30 and 60 then
    raise exception using errcode = '22023', message = 'invalid_checkin_window';
  end if;
  if coalesce(p_gps_enabled, false) and (
    p_latitude is null or p_latitude not between -90 and 90
    or p_longitude is null or p_longitude not between -180 and 180
    or p_radius_meters is null or p_radius_meters not between 50 and 2000
    or p_max_accuracy_meters is null or p_max_accuracy_meters not between 20 and 500
  ) then
    raise exception using errcode = '22023', message = 'invalid_checkin_location';
  end if;
  if exists (
    select 1
    from public.event_checkin_sessions
    where event_id = p_event_id
      and club_id = p_club_id
      and session_status = 'active'
  ) or exists (
    select 1
    from public.event_checkin_settings
    where event_id = p_event_id
      and club_id = p_club_id
      and now() between opens_at and closes_at
  ) then
    raise exception using errcode = '55000', message = 'checkin_session_active';
  end if;

  insert into public.event_checkin_settings (
    event_id, club_id, gps_enabled, qr_enabled, latitude, longitude,
    radius_meters, max_accuracy_meters, opens_at, closes_at,
    qr_rotation_seconds, configured_by_app_account_id
  ) values (
    p_event_id, p_club_id, coalesce(p_gps_enabled, false), coalesce(p_qr_enabled, false),
    case when p_gps_enabled then p_latitude else null end,
    case when p_gps_enabled then p_longitude else null end,
    case when p_gps_enabled then p_radius_meters else null end,
    case when p_gps_enabled then p_max_accuracy_meters else null end,
    p_opens_at, p_closes_at, p_qr_rotation_seconds, actor_id
  )
  on conflict (event_id) do update
  set gps_enabled = excluded.gps_enabled,
    qr_enabled = excluded.qr_enabled,
    latitude = excluded.latitude,
    longitude = excluded.longitude,
    radius_meters = excluded.radius_meters,
    max_accuracy_meters = excluded.max_accuracy_meters,
    opens_at = excluded.opens_at,
    closes_at = excluded.closes_at,
    qr_rotation_seconds = excluded.qr_rotation_seconds,
    configured_by_app_account_id = excluded.configured_by_app_account_id,
    updated_at = now()
  returning * into saved;

  insert into public.audit_logs (
    club_id, actor_app_account_id, action_key, subject_type, subject_id, metadata
  ) values (
    p_club_id, actor_id, 'attendance.settings_updated', 'club_event', p_event_id,
    jsonb_build_object(
      'gps_enabled', saved.gps_enabled,
      'qr_enabled', saved.qr_enabled,
      'radius_meters', saved.radius_meters,
      'max_accuracy_meters', saved.max_accuracy_meters,
      'opens_at', saved.opens_at,
      'closes_at', saved.closes_at,
      'qr_rotation_seconds', saved.qr_rotation_seconds
    )
  );

  return to_jsonb(saved) - 'latitude' - 'longitude';
end;
$$;

create or replace function public.start_event_checkin_session(
  p_club_id uuid,
  p_event_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  actor_id uuid := public.current_app_account_id();
  setting public.event_checkin_settings;
  target_event public.club_events;
  current_session public.event_checkin_sessions;
begin
  if actor_id is null or not public.current_can_manage_event_checkin(p_club_id) then
    raise exception using errcode = '42501', message = 'attendance_manage_required';
  end if;

  select event.* into target_event
  from public.club_events as event
  where event.id = p_event_id and event.club_id = p_club_id
  for update;
  select * into setting
  from public.event_checkin_settings
  where event_id = p_event_id and club_id = p_club_id;

  if target_event.id is null or setting.event_id is null or not setting.qr_enabled
     or target_event.event_status <> 'published'
     or not target_event.counts_for_attendance then
    raise exception using errcode = '22023', message = 'event_not_checkin_eligible';
  end if;
  if now() < setting.opens_at or now() > setting.closes_at then
    raise exception using errcode = '22023', message = 'checkin_window_closed';
  end if;

  select * into current_session
  from public.event_checkin_sessions
  where event_id = p_event_id and session_status = 'active'
  for update;

  if found and current_session.expires_at <= now() then
    update public.event_checkin_sessions
    set session_status = 'closed', closed_at = now(), close_reason = 'expired',
      closed_by_app_account_id = actor_id
    where id = current_session.id;
    current_session := null;
  elsif found then
    return jsonb_build_object(
      'session_id', current_session.id,
      'expires_at', current_session.expires_at,
      'idempotent', true
    );
  end if;

  insert into public.event_checkin_sessions (
    club_id, event_id, token_hash, token_prefix, opens_at, expires_at,
    created_by_app_account_id
  ) values (
    p_club_id, p_event_id, null, null, now(), setting.closes_at, actor_id
  ) returning * into current_session;

  insert into public.audit_logs (
    club_id, actor_app_account_id, action_key, subject_type, subject_id,
    metadata
  ) values (
    p_club_id, actor_id, 'attendance.session_opened', 'event_checkin_session',
    current_session.id,
    jsonb_build_object('event_id', p_event_id, 'expires_at', current_session.expires_at, 'version', 2)
  );

  return jsonb_build_object(
    'session_id', current_session.id,
    'expires_at', current_session.expires_at,
    'idempotent', false
  );
end;
$$;

create or replace function public.issue_event_checkin_qr(
  p_club_id uuid,
  p_event_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth, extensions
as $$
declare
  actor_id uuid := public.current_app_account_id();
  setting public.event_checkin_settings;
  current_session public.event_checkin_sessions;
  credential public.event_checkin_qr_credentials;
  raw_token text;
begin
  if actor_id is null or not public.current_can_manage_event_checkin(p_club_id) then
    raise exception using errcode = '42501', message = 'attendance_manage_required';
  end if;

  select * into setting
  from public.event_checkin_settings
  where event_id = p_event_id and club_id = p_club_id and qr_enabled;
  select * into current_session
  from public.event_checkin_sessions
  where event_id = p_event_id and club_id = p_club_id and session_status = 'active'
  for update;

  if setting.event_id is null or current_session.id is null
     or now() < setting.opens_at or now() > setting.closes_at
     or current_session.expires_at <= now() then
    raise exception using errcode = '22023', message = 'checkin_session_not_active';
  end if;

  update public.event_checkin_qr_credentials
  set invalidated_at = now()
  where session_id = current_session.id
    and invalidated_at is null
    and expires_at > now();

  raw_token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into public.event_checkin_qr_credentials (
    session_id, club_id, event_id, token_hash, token_prefix,
    expires_at, issued_by_app_account_id
  ) values (
    current_session.id, p_club_id, p_event_id,
    encode(extensions.digest(raw_token, 'sha256'), 'hex'), left(raw_token, 8),
    least(
      now() + make_interval(secs => setting.qr_rotation_seconds),
      setting.closes_at,
      current_session.expires_at
    ),
    actor_id
  ) returning * into credential;

  return jsonb_build_object(
    'session_id', current_session.id,
    'token', raw_token,
    'expires_at', credential.expires_at,
    'rotation_seconds', setting.qr_rotation_seconds
  );
end;
$$;

create or replace function public.close_event_checkin(
  p_club_id uuid,
  p_event_id uuid,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  actor_id uuid := public.current_app_account_id();
  current_session public.event_checkin_sessions;
  reason text := btrim(coalesce(p_reason, ''));
  has_session boolean := false;
begin
  if actor_id is null or not public.current_can_manage_event_checkin(p_club_id) then
    raise exception using errcode = '42501', message = 'attendance_manage_required';
  end if;
  if reason = '' or char_length(reason) > 500 then
    raise exception using errcode = '22023', message = 'invalid_checkin_close_reason';
  end if;

  select * into current_session
  from public.event_checkin_sessions
  where event_id = p_event_id and club_id = p_club_id and session_status = 'active'
  for update;
  has_session := found;

  if not exists (
    select 1 from public.event_checkin_settings
    where event_id = p_event_id and club_id = p_club_id
  ) then
    raise exception using errcode = 'P0002', message = 'checkin_settings_not_available';
  end if;

  if has_session then
    update public.event_checkin_qr_credentials
    set invalidated_at = coalesce(invalidated_at, now())
    where session_id = current_session.id and invalidated_at is null;

    update public.event_checkin_sessions
    set session_status = 'closed', closed_at = now(), close_reason = reason,
      closed_by_app_account_id = actor_id
    where id = current_session.id;
  end if;

  update public.event_checkin_settings
  set closes_at = least(closes_at, now()), updated_at = now(),
    configured_by_app_account_id = actor_id
  where event_id = p_event_id and club_id = p_club_id;

  insert into public.audit_logs (
    club_id, actor_app_account_id, action_key, subject_type, subject_id,
    metadata
  ) values (
    p_club_id, actor_id,
    case when has_session then 'attendance.session_closed' else 'attendance.checkin_closed' end,
    case when has_session then 'event_checkin_session' else 'club_event' end,
    case when has_session then current_session.id else p_event_id end,
    jsonb_build_object('event_id', p_event_id, 'reason', reason, 'version', 2)
  );
end;
$$;

create or replace function public.preview_event_qr_checkin(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth, extensions
as $$
declare
  actor_id uuid := public.current_app_account_id();
  credential public.event_checkin_qr_credentials;
  current_session public.event_checkin_sessions;
  target_event public.club_events;
  setting public.event_checkin_settings;
  actor_membership_id uuid;
  recent_attempts integer;
begin
  if actor_id is null then
    raise exception using errcode = '42501', message = 'active_account_required';
  end if;
  select count(*)::integer into recent_attempts
  from public.event_checkin_attempts
  where actor_app_account_id = actor_id
    and created_at > now() - interval '1 minute';
  if recent_attempts >= 20 then
    perform public.record_event_checkin_attempt(
      null, null, null, actor_id, 'qr', 'rate_limited'
    );
    return jsonb_build_object('status', 'rate_limited');
  end if;

  if p_token is null or p_token !~ '^[0-9a-f]{64}$' then
    perform public.record_event_checkin_attempt(
      null, null, null, actor_id, 'qr', 'credential_invalid'
    );
    return jsonb_build_object('status', 'credential_invalid');
  end if;

  select * into credential
  from public.event_checkin_qr_credentials
  where token_hash = encode(extensions.digest(p_token, 'sha256'), 'hex');
  if not found then
    perform public.record_event_checkin_attempt(
      null, null, null, actor_id, 'qr', 'credential_invalid'
    );
    return jsonb_build_object('status', 'credential_invalid');
  end if;

  actor_membership_id := public.current_checkin_membership_id(credential.club_id);
  if actor_membership_id is null then
    perform public.record_event_checkin_attempt(
      credential.club_id, credential.event_id, null, actor_id, 'qr', 'not_eligible'
    );
    return jsonb_build_object('status', 'not_eligible');
  end if;

  select * into current_session
  from public.event_checkin_sessions
  where id = credential.session_id;
  select * into setting
  from public.event_checkin_settings
  where event_id = credential.event_id and club_id = credential.club_id;
  select * into target_event
  from public.club_events
  where id = credential.event_id and club_id = credential.club_id;

  if credential.invalidated_at is not null or credential.expires_at <= now() then
    perform public.record_event_checkin_attempt(
      credential.club_id, credential.event_id, actor_membership_id, actor_id, 'qr', 'credential_expired'
    );
    return jsonb_build_object('status', 'credential_expired');
  end if;
  if current_session.id is null or current_session.session_status <> 'active'
     or current_session.expires_at <= now() then
    perform public.record_event_checkin_attempt(
      credential.club_id, credential.event_id, actor_membership_id, actor_id, 'qr', 'session_closed'
    );
    return jsonb_build_object('status', 'session_closed');
  end if;
  if target_event.id is null or setting.event_id is null or not setting.qr_enabled
     or now() < setting.opens_at or now() > setting.closes_at
     or target_event.event_status <> 'published'
     or not target_event.counts_for_attendance then
    perform public.record_event_checkin_attempt(
      credential.club_id, credential.event_id, actor_membership_id, actor_id, 'qr', 'window_closed'
    );
    return jsonb_build_object('status', 'window_closed');
  end if;

  return jsonb_build_object(
    'status', 'ready',
    'event_id', target_event.id,
    'title', target_event.title,
    'location', target_event.location,
    'starts_at', target_event.starts_at,
    'ends_at', target_event.ends_at,
    'credential_expires_at', credential.expires_at
  );
end;
$$;

create or replace function public.confirm_event_qr_checkin(p_token text)
