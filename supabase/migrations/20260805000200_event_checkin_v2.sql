    'camera_permission_denied', 'camera_unsupported', 'camera_error'
  ) then
    raise exception using errcode = '22023', message = 'invalid_client_checkin_failure';
  end if;

  select * into event from public.club_events where id = p_event_id;
  if actor_id is null or event.id is null then
    raise exception using errcode = '42501', message = 'checkin_not_eligible';
  end if;
  membership_id := public.current_checkin_membership_id(event.club_id);
  if membership_id is null then
    raise exception using errcode = '42501', message = 'checkin_not_eligible';
  end if;
  select * into setting from public.event_checkin_settings
  where event_id = event.id and club_id = event.club_id;
  if setting.event_id is null
     or (p_method = 'gps' and not setting.gps_enabled)
     or (p_method = 'qr' and not setting.qr_enabled) then
    raise exception using errcode = '42501', message = 'checkin_method_not_available';
  end if;
  if (
    select count(*) from public.event_checkin_attempts as attempt
    where attempt.actor_app_account_id = actor_id
      and attempt.event_id = event.id
      and attempt.created_at > now() - interval '1 minute'
  ) >= 20 then return; end if;

  perform public.record_event_checkin_attempt(
    event.club_id, event.id, membership_id, actor_id,
    p_method, p_result_code, null, null,
    jsonb_build_object('source', 'member_client')
  );
end;
$$;

create or replace function public.protect_event_attendance_update()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if old.id is distinct from new.id
     or old.club_id is distinct from new.club_id
     or old.event_id is distinct from new.event_id
     or old.membership_id is distinct from new.membership_id
     or old.checkin_session_id is distinct from new.checkin_session_id
     or old.checkin_method is distinct from new.checkin_method
     or old.checked_in_at is distinct from new.checked_in_at
     or old.checked_in_by_app_account_id is distinct from new.checked_in_by_app_account_id
     or old.checkin_note is distinct from new.checkin_note
     or old.location_accuracy_meters is distinct from new.location_accuracy_meters
     or old.distance_meters is distinct from new.distance_meters
     or old.created_at is distinct from new.created_at then
    raise exception using errcode = '23514', message = 'event_attendance_immutable_field';
  end if;
  if old.attendance_status = 'revoked' and new.attendance_status <> 'revoked' then
    raise exception using errcode = '23514', message = 'revoked_attendance_cannot_restore';
  end if;
  new.updated_at := now();
  if new.attendance_status = 'revoked' then
    new.revoked_at := coalesce(old.revoked_at, new.revoked_at, now());
    new.revoke_reason := btrim(coalesce(new.revoke_reason, ''));
    if new.revoked_by_app_account_id is null or new.revoke_reason = '' then
      raise exception using errcode = '23514', message = 'attendance_revoke_metadata_required';
    end if;
  end if;
  return new;
end;
$$;

